#!/usr/bin/env python3
from qemu_test import Guest
count=0
with Guest('files-editor') as g:
    def run(c,*e,marker='OS> '):
        global count
        text=g.send(c,e,marker);count+=1;return text
    run('mkdir a','CARPETA CREADA')
    run('crear a/one hola','ARCHIVO GUARDADO')
    run('copy a/one a/two','OPERACION OK')
    run('copy a/one a/two','ERROR:')
    run('ren a/two three','OPERACION OK')
    run('open a/three','hola')
    run('rmdir a','CARPETA NO VACIA')
    run('rm a','TIPO INCORRECTO')
    run('rm /','ES RAIZ')
    run('crear a/one/illegal no','CARPETA DESTINO INVALIDA')
    run('mkdir '+('z'*32),'ERROR:')
    run('open '+('z'*128),'ARCHIVO NO ENCONTRADO')
    run('tree /','three','one')
    # Arbol de arranque: documentacion propia y una ficha por cada imagen
    # empaquetada, con el mismo nombre que el archivo de images/.
    run('ls docs','COMANDOS.txt','ARCHIVOS.txt')
    run('open docs/ARCHIVOS.txt','SISTEMA DE ARCHIVOS')
    run('ls wallpapers','wallpaper.jpg','Logo.jpg')
    run('open wallpapers/Logo.jpg','Imagen empaquetada: Logo','Resolucion: 1200x1200')
    run('rm wallpapers/Logo.jpg','SOLO LECTURA')
    run('tree /','docs','wallpapers')
    run('rm a/three','OPERACION OK')
    run('rm a/one','OPERACION OK')
    run('rmdir a','OPERACION OK')
    run('edit note','EDITOR',marker='EDIT> ')
    run('int main(){',marker='EDIT> ')
    run('return 41;',marker='EDIT> ')
    run('}',marker='EDIT> ')
    run(':line 2 return 42;',marker='EDIT> ')
    run(':wq','ARCHIVO GUARDADO')
    run('open note','return 42;')
    run('run cpp note','(main): 42')
    run('edit note',marker='EDIT> ')
    run(':clear',marker='EDIT> ')
    run('HALT',marker='EDIT> ')
    run(':q','EDICION CANCELADA')
    run('open note','return 42;')
    run('edit empty',marker='EDIT> ')
    run(':wq','ARCHIVO GUARDADO')
    run('open empty')
    run('edit limit',marker='EDIT> ')
    run('x'*1022,marker='EDIT> ')
    run('y','LIMITE 1023',marker='EDIT> ')
    run(':wq','ARCHIVO GUARDADO')
    text=run('ls','limit (1023 B)')
    run('crear too '+('y'*1024),'CONTENIDO EXCEDE')
    run('eco '+('q'*1153),'LINEA DEMASIADO LARGA')
    run('suma 1 2','= 3')
print(f'PASSED: {count} comprobaciones seriales archivos/editor')
